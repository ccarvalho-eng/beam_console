import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";

const root = new URL("../../", import.meta.url);
const checkOnly = process.argv.includes("--check");

const javascriptSources = [
  "assets/js/imports.mjs",
  "assets/js/environment.mjs",
  "assets/js/graph_style.mjs",
  "assets/js/theme_hook.mjs",
  "assets/js/tree_hook.mjs",
  "assets/js/panel_hook.mjs",
  "assets/js/graph_hook.mjs",
  "assets/js/chart_hook.mjs",
  "assets/js/bootstrap.mjs"
];

const stylesheetSources = [
  "assets/css/base.css",
  "assets/css/tree.css",
  "assets/css/process_map.css",
  "assets/css/lifecycle.css",
  "assets/css/charts.css",
  "assets/css/responsive.css"
];

const read = path => readFile(new URL(path, root), "utf8");

const concatenate = async (banner, paths) => {
  const sources = await Promise.all(paths.map(read));
  return `${banner}\n${sources.map(source => source.trimEnd()).join("\n\n")}\n`;
};

const outputs = new Map([
  [
    "priv/static/beam_console.mjs",
    await concatenate("// Generated by assets/scripts/build.mjs. Do not edit.", javascriptSources)
  ],
  [
    "priv/static/beam_console.css",
    await concatenate("/* Generated by assets/scripts/build.mjs. Do not edit. */", stylesheetSources)
  ],
  [
    "priv/static/beam_console_support.mjs",
    await concatenate(
      "// Generated by assets/scripts/build.mjs. Do not edit.",
      ["assets/js/support.mjs"]
    )
  ],
  [
    "priv/static/beam_console_theme.js",
    await concatenate(
      "// Generated by assets/scripts/build.mjs. Do not edit.",
      ["assets/js/theme_bootstrap.js"]
    )
  ]
]);

for (const [path, expected] of outputs) {
  if (checkOnly) {
    assert.equal(
      await read(path),
      expected,
      `${path} is stale; run npm run build from assets`
    );
  } else {
    await writeFile(new URL(path, root), expected);
  }
}
